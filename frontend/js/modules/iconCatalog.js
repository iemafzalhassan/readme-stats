export function getIconById(id) {
  return ICON_CATALOG.find((item) => item.id === id);
}

// Guaranteed non-broken thumbnail URL using Iconify universal SVG endpoint
export function getIconThumbnailUrl(icon, tintHex = "") {
  const color = (tintHex || icon.color || "6366f1").replace("#", "");
  const path = (icon.iconify || `simple-icons:${icon.simpleIcon}`).replace(
    ":",
    "/",
  );
  return `https://api.iconify.design/${path}.svg?color=%23${color}`;
}

export function renderTechStackMarkdown({
  selectedIds = [],
  provider = "skillicons",
  shape = "dark",
  size = 40,
  perline = 8,
  themeName = "tokyonight",
  themeColors = {},
  themeSync = false,
  baseUrl = "",
}) {
  const icons = selectedIds.map(getIconById).filter(Boolean);
  if (icons.length === 0) return "";

  const cleanHex = (c, fallback = "70a5fd") =>
    (c || fallback).toString().replace("#", "").split(",")[0];

  const iconHex = cleanHex(themeColors.icon_color, "70a5fd");
  const titleHex = cleanHex(themeColors.title_color, "bf91f3");
  const bgHex = cleanHex(themeColors.bg_color, "1a1b27");

  if (provider === "skillicons") {
    const slugs = [...new Set(icons.map((i) => i.skillIcon).filter(Boolean))];
    const mode = shape === "light" ? "light" : "dark";
    const url = `https://skillicons.dev/icons?i=${slugs.join(",")}&theme=${mode}&perline=${perline}`;
    return `<p align="center">\n  <a href="https://skillicons.dev">\n    <img src="${url}" alt="Tech Stack" />\n  </a>\n</p>`;
  }

  if (provider === "edgeops-svg") {
    const keys = icons.map((i) => i.id).join(",");
    const validShape = [
      "hexagon",
      "squircle",
      "circle",
      "pill",
      "glass",
    ].includes(shape)
      ? shape
      : "hexagon";
    const host = baseUrl || window.location.origin;
    const url = `${host}/api/badges?icons=${encodeURIComponent(keys)}&shape=${validShape}&theme=${encodeURIComponent(themeName)}&perline=${Math.min(perline, 8)}`;
    return `<p align="center">\n  <img src="${url}" alt="Architecture & Tech Stack" />\n</p>`;
  }

  if (provider === "shields") {
    const badgeStyle = [
      "for-the-badge",
      "flat-square",
      "flat",
      "plastic",
    ].includes(shape)
      ? shape
      : "for-the-badge";
    const badges = icons.map((icon) => {
      const badgeBg = themeSync ? bgHex : icon.color;
      const logoClr = themeSync ? iconHex : "white";
      const label = encodeURIComponent(icon.name).replace(/-/g, "--");
      return `  <img src="https://img.shields.io/badge/${label}-${badgeBg}?style=${badgeStyle}&logo=${icon.simpleIcon}&logoColor=${logoClr}" alt="${icon.name}" />`;
    });
    return `<p align="center">\n${badges.join("\n")}\n</p>`;
  }

  if (provider === "iconify" || provider === "simpleicons") {
    const items = icons.map((icon) => {
      let tint = icon.color;
      if (themeSync || shape === "theme-icon") tint = iconHex;
      else if (shape === "theme-title") tint = titleHex;
      else if (shape === "white") tint = "ffffff";
      const url = getIconThumbnailUrl(icon, tint);
      return `  <img src="${url}" width="${size}" height="${size}" alt="${icon.name}" title="${icon.name}" />`;
    });
    return `<p align="center">\n${items.join("&nbsp;&nbsp;&nbsp;")}\n</p>`;
  }

  if (provider === "devicon") {
    const items = icons.map((icon) => {
      const tint = themeSync ? iconHex : icon.color;
      const url = getIconThumbnailUrl(icon, tint);
      return `  <img src="${url}" width="${size}" height="${size}" alt="${icon.name}" title="${icon.name}" />`;
    });
    return `<p align="center">\n${items.join("&nbsp;&nbsp;&nbsp;")}\n</p>`;
  }

  return "";
}
